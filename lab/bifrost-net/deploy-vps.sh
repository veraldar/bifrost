#!/usr/bin/env bash
# Ship the bifrost-net ACCESS POINT to the VPS and point this box's bridge at it.
# Runs HERE (the box). The VPS is reached over ssh; the box itself never listens
# for the internet — its bridge dials OUT to the ap. Read deploy-vps.md first.
#
#   ./deploy-vps.sh sni      nginx keeps :443 for the site; its `stream` block passes
#                            SNI sandbox.veraldar.org to the ap on 127.0.0.1:8443 (PROXY v1)
#   ./deploy-vps.sh direct   the ap owns :443 itself (a dedicated IP: AP_LISTEN=<ip>:443)
#
# Env:  VPS_HOST (veraldar)  AP_DOMAIN (sandbox.veraldar.org)  AP_LISTEN (mode default)
#       BRIDGE_TOML (~/.local/state/bifrost-bridge/bridge.toml)  AP_UPSTREAM (127.0.0.1:8090)
#       AP_LIVEKIT (unset; e.g. 127.0.0.1:7880 → /rtc goes to LiveKit signaling)
#       AP_ICE_TCP (unset; e.g. 7881 → VPS tcp/7881 forwarded raw to LiveKit ICE-TCP on the box)
#       AP_BUILD=remote  build on the VPS instead (when its glibc < 2.38 — preflight says so)
#       DRY_RUN=1        print the remote commands, change nothing anywhere
set -euo pipefail
cd "$(dirname "$0")"

MODE=${1:-}
case "$MODE" in
  sni)    LISTEN=${AP_LISTEN:-127.0.0.1:8443}; PP=true ;;
  direct) LISTEN=${AP_LISTEN:-0.0.0.0:443};    PP=false ;;
  *) echo "usage: $0 sni|direct   (see deploy-vps.md)"; exit 2 ;;
esac
VPS=${VPS_HOST:-veraldar}
DOMAIN=${AP_DOMAIN:-sandbox.veraldar.org}
LE=/etc/letsencrypt/live/$DOMAIN
BRIDGE_TOML=${BRIDGE_TOML:-$HOME/.local/state/bifrost-bridge/bridge.toml}
UPSTREAM=${AP_UPSTREAM:-127.0.0.1:8090}
BIN=target/release/bifrost-net
run() { if [ -n "${DRY_RUN:-}" ]; then echo "  [dry] ssh $VPS -- $*"; else ssh "$VPS" "$@"; fi; }
put() { if [ -n "${DRY_RUN:-}" ]; then echo "  [dry] scp $1 → $VPS:$2"; else scp -q "$1" "$VPS:$2"; fi; }

echo "== bifrost-net ap → $VPS  ($DOMAIN, mode $MODE, listen $LISTEN)"
cargo build --release -q

# 0. preflight — the cert is the website session's step (certbot), not ours
echo "-- preflight"
run "sudo test -r $LE/fullchain.pem && sudo test -r $LE/privkey.pem" \
  || { echo "BLOCKED: $LE missing on $VPS — issue the cert first (deploy-vps.md §1)"; exit 1; }
if [ -z "${DRY_RUN:-}" ]; then
  GLIBC=$(ssh "$VPS" "ldd --version | head -1 | grep -o '[0-9]*\.[0-9]*\$'")
  echo "   vps glibc $GLIBC (binary needs ≥ 2.38 + libopus0)"
  if [ "${AP_BUILD:-local}" = local ] && [ "$(printf '%s\n2.38\n' "$GLIBC" | sort -V | head -1)" != 2.38 ]; then
    echo "BLOCKED: VPS glibc $GLIBC < 2.38 — rerun with AP_BUILD=remote (needs rustup + libopus-dev there)"; exit 1
  fi
fi

# 1. pairing credential: raw → this box only; the VPS keeps its sha-256
TOK=$("$BIN" ap-token)
RAW=$(echo "$TOK" | sed -n 's/^token = "\([0-9a-f]*\)".*/\1/p')
HASH=$(echo "$TOK" | sed -n 's/^bridge_token_sha256 = "\([0-9a-f]*\)".*/\1/p')

# 2. the ap: binary, config, systemd unit (DynamicUser; certbot's root-only key arrives
#    through LoadCredential, re-read on every restart — the renewal hook restarts us)
STAGE=$(mktemp -d); trap 'rm -rf "$STAGE"' EXIT
cat > "$STAGE/ap.toml" <<EOF
# bifrost-net access point — $DOMAIN ($MODE mode). Generated by deploy-vps.sh.
[ap]
listen = "$LISTEN"
cert_path = "/run/credentials/bifrost-ap.service/cert"
key_path = "/run/credentials/bifrost-ap.service/key"
bridge_token_sha256 = "$HASH"
proxy_protocol = $PP
EOF
if [ -n "${AP_ICE_TCP:-}" ]; then
  printf '\n[[ap.tcp]]\nname = "livekit-ice"\nlisten = "0.0.0.0:%s"\n' "$AP_ICE_TCP" >> "$STAGE/ap.toml"
fi
cat > "$STAGE/bifrost-ap.service" <<EOF
[Unit]
Description=bifrost-net access point ($DOMAIN)
After=network-online.target
Wants=network-online.target

[Service]
ExecStart=/usr/local/bin/bifrost-net ap -c /etc/bifrost-ap/ap.toml
LoadCredential=cert:$LE/fullchain.pem
LoadCredential=key:$LE/privkey.pem
DynamicUser=yes
AmbientCapabilities=CAP_NET_BIND_SERVICE
CapabilityBoundingSet=CAP_NET_BIND_SERVICE
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
Restart=always
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF
cat > "$STAGE/bifrost-ap-renew.sh" <<'EOF'
#!/bin/sh
# certbot deploy hook: new cert files → restart the ap (LoadCredential re-reads them)
systemctl restart bifrost-ap.service
EOF

echo "-- install on $VPS"
if [ "${AP_BUILD:-local}" = remote ]; then
  if [ -n "${DRY_RUN:-}" ]; then echo "  [dry] rsync src/ Cargo.toml Cargo.lock → $VPS:bifrost-net-src/ + cargo build --release"
  else
    rsync -a --delete src Cargo.toml Cargo.lock "$VPS:bifrost-net-src/"
    ssh "$VPS" "cd bifrost-net-src && . \$HOME/.cargo/env && cargo build --release -q && cp target/release/bifrost-net /tmp/bifrost-net.new"
  fi
else
  put "$BIN" /tmp/bifrost-net.new
fi
put "$STAGE/ap.toml" /tmp/ap.toml.new
put "$STAGE/bifrost-ap.service" /tmp/bifrost-ap.service.new
put "$STAGE/bifrost-ap-renew.sh" /tmp/bifrost-ap-renew.sh.new
run "set -e
  sudo install -m 755 /tmp/bifrost-net.new /usr/local/bin/bifrost-net
  sudo install -d -m 755 /etc/bifrost-ap
  sudo install -m 644 /tmp/ap.toml.new /etc/bifrost-ap/ap.toml
  sudo install -m 644 /tmp/bifrost-ap.service.new /etc/systemd/system/bifrost-ap.service
  sudo install -D -m 755 /tmp/bifrost-ap-renew.sh.new /etc/letsencrypt/renewal-hooks/deploy/bifrost-ap.sh
  rm -f /tmp/bifrost-net.new /tmp/ap.toml.new /tmp/bifrost-ap.service.new /tmp/bifrost-ap-renew.sh.new
  /usr/local/bin/bifrost-net ap-token >/dev/null   # the binary runs here (glibc/libopus ok)
  sudo systemctl daemon-reload
  sudo systemctl enable --now bifrost-ap.service
  sudo systemctl restart bifrost-ap.service
  sleep 1; sudo systemctl is-active bifrost-ap.service
  sudo journalctl -u bifrost-ap.service -n 4 --no-pager"

# 3. the pin: from the PUBLIC leaf cert (stable across renewals with --reuse-key, §1)
if [ -n "${DRY_RUN:-}" ]; then PIN="sha-256 <from $LE/cert.pem>"
else
  ssh "$VPS" "sudo cat $LE/cert.pem" > "$STAGE/leaf.pem"
  PIN=$("$BIN" ap-pin "$STAGE/leaf.pem" | sed -n 's/^pin = "\(.*\)"/\1/p')
fi
echo "   ap identity: $PIN"

# 4. this box: [ap] into bridge.toml (replaced if present), restart the bridge
echo "-- bridge on this box ($BRIDGE_TOML)"
SECTION="[ap]
url = \"wss://$DOMAIN/ap\"
pin = \"$PIN\"
token = \"$RAW\"
upstream = \"$UPSTREAM\""
[ -n "${AP_LIVEKIT:-}" ] && SECTION="$SECTION
livekit = \"$AP_LIVEKIT\""
[ -n "${AP_ICE_TCP:-}" ] && SECTION="$SECTION
tcp = { livekit-ice = \"127.0.0.1:$AP_ICE_TCP\" }"
if [ -n "${DRY_RUN:-}" ]; then
  echo "  [dry] would write into $BRIDGE_TOML:"; echo "$SECTION" | sed 's/^token = .*/token = "<raw, 64 hex>"/; s/^/    /'
else
  cp "$BRIDGE_TOML" "$BRIDGE_TOML.bak.$(date +%s)"
  python3 - "$BRIDGE_TOML" "$SECTION" <<'PY'
import re, sys
p, section = sys.argv[1], sys.argv[2]
s = open(p).read()
s = re.sub(r'(?ms)^\[ap\]\n.*?(?=^\[|\Z)', '', s).rstrip() + "\n\n" + section + "\n"
open(p, "w").write(s)
PY
  chmod 600 "$BRIDGE_TOML"
  systemctl --user restart bifrost-bridge.service
  for _ in $(seq 50); do journalctl --user -u bifrost-bridge.service -n 20 --no-pager | grep -q "channel up" && break; sleep 0.2; done
  journalctl --user -u bifrost-bridge.service -n 20 --no-pager | grep -E "ap:|channel" | tail -3
fi

# 5. from outside: the phone's view
if [ -z "${DRY_RUN:-}" ]; then
  CODE=$(curl -s -o /dev/null -w '%{http_code}' "https://$DOMAIN/")
  HSTS=$(curl -sI "https://$DOMAIN/" | grep -ci '^strict-transport-security')
  API=$(curl -s -o /dev/null -w '%{http_code}' "https://$DOMAIN/api/session")
  echo "   https://$DOMAIN/ → $CODE (HSTS $HSTS) | /api/session uncredentialed → $API (want 401)"
  [ "$CODE" = 200 ] && [ "$HSTS" = 1 ] && [ "$API" = 401 ] && echo "DEPLOY: GREEN" || { echo "DEPLOY: CHECK (see deploy-vps.md §5)"; exit 1; }
fi
